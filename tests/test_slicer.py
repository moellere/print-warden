import json

from print_warden.slicer import flatten, parse_gcode_header

HEADER = """; generated by OrcaSlicer
; estimated printing time (normal mode) = 1h 2m 3s
; total layer number: 120
; max_z_height: 24.00
G28
; filament used [mm] = 4567.8
; filament used [g] = 13.62
; total filament used [g] = 13.62
"""


def test_parse_header():
    meta = parse_gcode_header(HEADER)
    assert meta == {
        "est_seconds": 3723,
        "layers": 120,
        "max_z": 24.0,
        "filament_m": 4.57,
        "filament_g": 13.62,
    }


def test_flatten_resolves_inherits_and_overrides(tmp_path):
    d = tmp_path / "process"
    d.mkdir()
    (d / "base.json").write_text(json.dumps({"a": 1, "b": 1}))
    (d / "child.json").write_text(json.dumps({"inherits": "base", "b": 2, "c": 2}))
    assert flatten(tmp_path, "process", "child", {"c": 3}) == {"a": 1, "b": 2, "c": 3}
